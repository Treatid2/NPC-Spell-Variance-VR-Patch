#pragma once

#include <algorithm>
#include <array>
#include <cstddef>
#include <cstdint>
#include <span>

namespace nsv_patch {

inline constexpr std::array<std::uint8_t, 32> kExpectedDllSha256{
    0xF1, 0xCB, 0x34, 0xF2, 0x6F, 0x49, 0xFA, 0xFC, 0xB9, 0x81, 0xCA,
    0x55, 0xFA, 0x83, 0xE9, 0x11, 0x9E, 0x60, 0x6B, 0xBC, 0xE9, 0x3D,
    0x7A, 0x13, 0x5C, 0x60, 0xDC, 0xDE, 0xEA, 0xD4, 0x7C, 0xD6,
};

[[nodiscard]] constexpr bool
MatchesExpectedDllHash(std::span<const std::uint8_t, 32> a_digest) noexcept {
  return std::ranges::equal(a_digest, kExpectedDllSha256);
}

} // namespace nsv_patch
